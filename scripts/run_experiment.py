"""
Experiment harness.

Drives the experiment over a fixed query set (the 3 paper categories). For each item:
assign a unique context key, evaluate the `orchestrator` flag (LaunchDarkly splits the
variations once the experiment is running), dispatch to that framework's runner against
the SHARED graph, judge the output, and emit the quality metric. Graph/node metrics
(latency, tokens, cost, path, handoffs) flow automatically via the trackers.

    # full default sweep (flag-driven once the experiment is live)
    python scripts/run_experiment.py

    # smoke test before the experiment exists: force a framework, one context
    python scripts/run_experiment.py --framework langgraph --limit 1
"""

import argparse
import asyncio
import csv
import datetime
import importlib
import json
import logging
import os
import sys
import time
import warnings
from pathlib import Path

from tqdm import tqdm

project_root = Path(__file__).parent.parent
sys.path.insert(0, str(project_root))

from dotenv import load_dotenv
load_dotenv(project_root / ".env")

import ldclient
from ldclient import Context
from ldclient.config import Config
from ldai.client import LDAIClient

from shared.prompt import build_paper_prompt
from orchestrators.dispatcher import execute_graph

# Keep the terminal readable around the progress bar: route SDK and framework log chatter
# away from stdout — full per-run detail goes to the results CSV.
logging.getLogger("ldclient.util").setLevel(logging.ERROR)
warnings.filterwarnings("ignore")

JUDGE_METRIC = "$ld:ai:judge:gap-quality"

RUNNERS = {
    "langgraph": "orchestrators.langgraph_runner",
    "strands": "orchestrators.strands_runner",
    "openai-agents": "orchestrators.openai_agents_runner",
    "google-adk": "orchestrators.google_adk_runner",
}
GRAPH_KEY = "research-gap-graph"
FLAG_KEY = "orchestrator"
# The judge ($ld:ai:judge:gap-quality) generates its own metric — no custom metric here.

# Default query set: every topic file in data/ (one file = one topic = one category).
# Discovered dynamically so repulling/adding topics needs no code change. The combined_*
# file is the smoke-test sample (overlaps the topics), so it's excluded.
CATEGORIES = sorted(
    p.name for p in (project_root / "data").glob("*_papers.json")
    if not p.name.startswith("combined")
)


def load_category(fname, n=None):
    # Accept a bare filename (resolved under data/) or an existing path (used as-is),
    # so --data can point at a downloaded set anywhere.
    path = Path(fname)
    if not path.exists():
        path = project_root / "data" / fname
    data = json.load(open(path))
    papers = data if isinstance(data, list) else data.get("papers") or data.get("items") or []
    # Default: the FULL topic set — gap analysis must see every paper to find the topic's
    # real gaps; a subset would surface gaps that aren't actually there. n only caps for smoke
    # tests (explicit `is not None` so a passed 0 means "no papers", not "all papers").
    return papers[:n] if n is not None else papers


async def run_one(ld, ai_client, item_id, papers, override=None):
    # MULTI-context: "request" is the per-run unit for the AI/graph latency + token metrics and
    # the experiment's randomization unit; "user" keeps the user-unit autogenerated metrics (the
    # judge, success/error) populating. Each run is one user AND one request, so both share the id.
    def _ctx(orchestrator=None):
        ub = Context.builder(item_id).kind("user")
        rb = Context.builder(item_id).kind("request")
        if orchestrator:
            # The orchestrator attribute (a) routes each node config to that framework's native
            # model via node targeting, and (b) makes metrics attributable per framework in
            # Monitoring/Insights even outside the randomized experiment.
            ub.set("orchestrator", orchestrator)
            rb.set("orchestrator", orchestrator)
        return Context.create_multi(ub.build(), rb.build())

    # Evaluate the orchestrator flag (the experiment's randomized split, bucketed by the request
    # key) on a context WITHOUT the attribute, then resolve the framework.
    framework = override or ld.variation(FLAG_KEY, _ctx(), "langgraph")
    if framework not in RUNNERS:
        return {"id": item_id, "framework": framework, "path": "", "score": None,
                "error": f"no runner for '{framework}'"}

    # Run the graph on a context WITH orchestrator=framework so each node config's targeting
    # routes that node to the framework's native model (node configs are evaluated inside
    # execute_graph). Without this, node targeting keyed on `orchestrator` finds the attribute
    # absent and serves the fallthrough model to every framework in the randomized path.
    context = _ctx(framework)
    runner = importlib.import_module(RUNNERS[framework])
    user_input = build_paper_prompt(papers)
    try:
        result = await execute_graph(
            ai_client, GRAPH_KEY, context, user_input, runner.build_agent, runner.invoke,
            require_context_attr="orchestrator",
        )
    except Exception as e:
        return {"id": item_id, "framework": framework, "path": "", "score": None,
                "error": str(e)[:200]}

    # The dispatcher fired the attached judge (online evaluation) and recorded the score.
    score = result["judge_scores"].get(JUDGE_METRIC)
    return {"id": item_id, "framework": framework, "path": " > ".join(result["path"]),
            "score": score, "error": None}


async def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--papers-per-context", type=int, default=None,
                    help="cap papers per run (default: the FULL topic set — gap analysis "
                         "needs every paper; only cap for cheap smoke tests)")
    ap.add_argument("--runs-per-category", type=int, default=15)
    ap.add_argument("--framework", default=None, help="force a framework (override the flag)")
    ap.add_argument("--limit", type=int, default=None, help="cap total contexts (for smoke tests)")
    ap.add_argument("--data", nargs="+", default=None,
                    help="data file(s) to run over (e.g. a set from download_papers.py); "
                         "default = the shipped 3-category set")
    ap.add_argument("--all-frameworks", action="store_true",
                    help="matched mode: run EACH data set through ALL four orchestrators once "
                         "(apples-to-apples head-to-head) instead of the flag's randomized split")
    ap.add_argument("--concurrency", type=int, default=4,
                    help="how many contexts to run at once (runs are independent; lower if you "
                         "hit model-provider rate limits, raise on higher API tiers, 1 = serial)")
    args = ap.parse_args()

    ldclient.set_config(Config(os.environ["LD_SDK_KEY"]))
    for _ in range(12):
        if ldclient.get().is_initialized():
            break
        time.sleep(0.5)
    ld = ldclient.get()
    ai_client = LDAIClient(ld)

    # Build the job list (item_id, papers, override) for the chosen mode, then cap by --limit.
    jobs = []
    categories = args.data if args.data else CATEGORIES
    if not categories:
        sys.exit("No topic files found in data/ (and no --data given). "
                 "Download at least one: python scripts/download_papers.py --query 'ti:\"your niche\"'")
    # Announce the discovered topics — auto-discovery means a stray *_papers.json in data/
    # silently joins the experiment, so make the composition visible up front.
    print(f"Topics ({len(categories)}):")
    for fname in categories:
        print(f"  - {fname}")
    for fname in categories:
        papers = load_category(fname, args.papers_per_context)
        # Topic label = the filename stem (used in context keys and the results CSV).
        category = Path(fname).name.removesuffix("_papers.json").rstrip("_")
        if args.all_frameworks:
            # Matched head-to-head: every orchestrator analyzes the SAME full topic set, once.
            for fw in RUNNERS:
                jobs.append((f"{category}-{fw}", papers, fw))
        else:
            # Randomized split: the orchestrator flag assigns each context one framework.
            for r in range(args.runs_per_category):
                jobs.append((f"{category}-run{r}", papers, args.framework))
    if args.limit is not None:
        jobs = jobs[:args.limit]
    n = len(jobs)

    # Runs are independent → run up to --concurrency at once (semaphore-bounded for rate limits).
    # A progress bar replaces per-run prints; full detail goes to the CSV. Results accumulate as
    # runs finish, and the LD client is flushed in a `finally` so a Ctrl-C STILL records the
    # completed runs' flag exposures + metrics — otherwise a cancelled run drops its buffered
    # events and the experiment shows no traffic.
    sem = asyncio.Semaphore(max(1, args.concurrency))
    pbar = tqdm(total=n, desc="experiment", unit="run", ncols=88)
    results = []
    async def run_job(item_id, papers, override):
        async with sem:
            r = await run_one(ld, ai_client, item_id, papers, override=override)
            results.append(r)
            pbar.update(1)
            return r
    try:
        await asyncio.gather(*(run_job(*j) for j in jobs))
    except (KeyboardInterrupt, asyncio.CancelledError):
        print("\n⚠ cancelled — flushing the runs that finished")
    finally:
        pbar.close()
        ld.flush()
        ld.close()

    # Write every completed run (including failures) to a timestamped CSV.
    out_dir = project_root / "results"
    out_dir.mkdir(exist_ok=True)
    out_path = out_dir / f"experiment_{datetime.datetime.now():%Y%m%d_%H%M%S}.csv"
    with open(out_path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["id", "framework", "score", "path", "error"])
        w.writeheader()
        w.writerows(results)

    ok = [r for r in results if r["score"] is not None]
    failed = [r for r in results if r["score"] is None]
    print(f"\n{len(results)}/{n} runs done, {len(ok)} scored.  Results → {out_path.relative_to(project_root)}")
    if failed:
        print(f"  {len(failed)} failed: " + "; ".join(f"{r['id']} ({(r['error'] or '')[:50]})" for r in failed[:4]))
    if ok:
        by_fw = {}
        for r in ok:
            by_fw.setdefault(r["framework"], []).append(r["score"])
        print("  per-framework mean quality:")
        for fw, scores in sorted(by_fw.items()):
            print(f"    {fw:<14} n={len(scores):>2}  mean={sum(scores) / len(scores):.3f}")


if __name__ == "__main__":
    asyncio.run(main())
